/* 计算订单可用券 */
function applyCoupon(total, cat) {
  const usable = COUPONS.filter(c => (c.cat === '全部' || c.cat === cat) && total >= c.min);
  if (!usable.length) return { coupon: null, off: 0, total };
  const best = usable.sort((a, b) => b.off - a.off)[0];
  return { coupon: best, off: best.off, total: total - best.off };
}

